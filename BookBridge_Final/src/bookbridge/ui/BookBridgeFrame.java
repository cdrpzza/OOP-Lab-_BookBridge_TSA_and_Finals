    private void refreshBooks() {
        DefaultTableModel model =
                (DefaultTableModel) tblBooks.getModel();

        model.setRowCount(0);

        for (LibraryBook book : service.listBooks()) {
            model.addRow(new Object[]{
                book.getIsbn(),
                book.getTitle(),
                book.getStatus()
            });
        }
    }
    
    private void refreshMembers() {
        DefaultTableModel model =
                (DefaultTableModel) tblMembers.getModel();

        model.setRowCount(0);

        for (Member member : service.listMembers()) {
            model.addRow(new Object[]{
                member.getMemberId(),
                member.getMemberName(),
                member.getMembershipType(),
                member.getMaximumLoanDays(),
                member.getDailyFine()
            });
        }
    }
    
    private void refreshLoans() {
        DefaultTableModel model =
                (DefaultTableModel) tblLoans.getModel();

        model.setRowCount(0);

        for (LoanRecord loan : service.listActiveLoans()) {
            model.addRow(new Object[]{
                loan.getLoanId(),
                loan.getMember().getMemberName(),
                loan.getBook().getTitle(),
                loan.getLoanDate(),
                loan.getDueDate(),
                loan.getStatus()
            });
        }
    }
    
